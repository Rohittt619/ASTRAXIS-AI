class PayloadGenerator:
    """
    Generates adversarial injection payloads for red-teaming AI agent pipelines.

    Usage:
        generator = PayloadGenerator()

        # Get all payloads
        payloads = generator.generate_all()

        # Get only critical severity payloads
        critical = generator.generate_by_severity("critical")

        # Get only jailbreak category payloads
        jailbreaks = generator.generate_by_category(AttackCategory.JAILBREAK)
    """

    def generate_all(self) -> List[InjectionPayload]:
        """
        Generate the complete adversarial payload library.

        Returns:
            List of all InjectionPayload objects across all attack categories.
        """
        return [
            InjectionPayload(
                payload_id=str(uuid.uuid4()),
                category=t["category"],
                content=t["content"],
                severity=t["severity"],
                description=t["description"],
                obfuscated=t.get("obfuscated", False),
            )
            for t in _PAYLOAD_TEMPLATES
        ]

    def generate_by_category(self, category: AttackCategory) -> List[InjectionPayload]:
        """
        Generate payloads filtered to a specific attack category.

        Args:
            category: The AttackCategory enum value to filter by.

        Returns:
            List of InjectionPayload objects matching the category.
        """
        return [p for p in self.generate_all() if p.category == category]

    def generate_by_severity(self, severity: str) -> List[InjectionPayload]:
        """
        Generate payloads filtered by risk severity level.

        Args:
            severity: One of "low", "medium", "high", "critical".

        Returns:
            List of InjectionPayload objects matching the severity.
        """
        return [p for p in self.generate_all() if p.severity == severity]

    def generate_obfuscated(self) -> List[InjectionPayload]:
        """
        Generate only obfuscated payloads designed to bypass keyword filters.

        Returns:
            List of obfuscated InjectionPayload objects.
        """
        return [p for p in self.generate_all() if p.obfuscated]

    def summary(self) -> dict:
        """
        Return a statistical summary of the payload library.

        Returns:
            Dictionary with total count and breakdown by category and severity.
        """
        payloads = self.generate_all()
        return {
            "total_payloads": len(payloads),
            "by_category": {
                cat.value: len([p for p in payloads if p.category == cat])
                for cat in AttackCategory
            },
            "by_severity": {
                sev: len([p for p in payloads if p.severity == sev])
                for sev in ["low", "medium", "high", "critical"]
            },
            "obfuscated_count": len(self.generate_obfuscated()),
        }
